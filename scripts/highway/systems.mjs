import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
const root = fileURLToPath(new URL('../../', import.meta.url));
const read = (name) => readFileSync(path.join(root, name), 'utf8');
const json = (name) => JSON.parse(read(name));
const write = process.argv.includes('--write');
if (process.argv.slice(2).some(arg => arg !== '--write')) throw new Error('Usage: node scripts/highway/systems.mjs [--write]');
const catalog = json('catalog/components.json');
const standards = json('catalog/standards.json');
const errors = [];
const manifest = json('packages/highway-react/package.json');
if (catalog.packageVersion !== manifest.version) errors.push('Catalog/package version mismatch');
if (catalog.schemaVersion !== 1 || standards.schemaVersion !== 1) errors.push('Unsupported catalog/standards schema');
for (const component of catalog.components) {
  const contract = component.contract;
  if (!contract || !standards.families[contract.family] || !standards.motion[contract.motion] || !standards.materials[contract.material]) errors.push(`Missing/invalid contract for ${component.export}`);
  for (const example of component.examples ?? []) {
    if (!/^examples\/contracts\/[a-z][a-z0-9-]*\.tsx$/.test(example) || !existsSync(path.join(root, example))) errors.push(`Invalid example for ${component.export}`);
  }
}
if (errors.length) throw new Error(errors.join('\n'));
const report = ['# Highway component contracts', '', '> Generated by `npm run systems:update`. Edit catalog/components.json and catalog/standards.json.', '', standards.policy, '', '| Export | Family | Motion | Material |', '| --- | --- | --- | --- |'];
for (const c of catalog.components) report.push(`| ${c.export} | ${c.contract.family} | ${c.contract.motion} | ${c.contract.material} |`);
for (const [name, family] of Object.entries(standards.families)) report.push('', `## ${name}`, '', family.behavior, '', `Required review states: ${family.states.join(', ')}.`);
for (const [name, recipe] of Object.entries(standards.motion)) report.push('', `## Motion: ${name}`, '', recipe.purpose, '', recipe.policy, '', `Owner: \`${recipe.owner}\`.`);
function artifact(name, value) {
  if (write) { mkdirSync(path.dirname(path.join(root, name)), { recursive: true }); writeFileSync(path.join(root, name), value); }
  else if (!existsSync(path.join(root, name)) || read(name) !== value) errors.push(`${name} is stale. Run npm run systems:update and review the diff.`);
}
artifact('docs/COMPONENT-CONTRACTS.md', report.join('\n') + '\n');
const typesRoot = 'packages/highway-react/dist/types/packages/highway-react/src';
const declarations = {};
const printer = ts.createPrinter({ removeComments: true });
function visit(relative) {
  for (const item of readdirSync(path.join(root, relative), { withFileTypes: true }).sort((a,b) => a.name.localeCompare(b.name))) {
    const name = `${relative}/${item.name}`;
    if (item.isDirectory()) visit(name);
    else if (name.endsWith('.d.ts')) {
      const text = read(name);
      if (/never\[\]/.test(text)) errors.push(`${name}: unusable inferred never[] public declaration; annotate the source props`);
      declarations[name.slice(typesRoot.length + 1)] = printer.printFile(ts.createSourceFile(name, text, ts.ScriptTarget.Latest, true));
    }
  }
}
visit(typesRoot);
// Keep reader-facing API snippets scoped to one export and its local type dependencies.
function focusedDeclaration(text, name) {
  const file = ts.createSourceFile('reference.d.ts', text, ts.ScriptTarget.Latest, true);
  const names = new Map();
  for (const statement of file.statements) {
    if (statement.name && ts.isIdentifier(statement.name)) names.set(statement.name.text, statement);
    if (ts.isVariableStatement(statement)) for (const declaration of statement.declarationList.declarations) {
      if (ts.isIdentifier(declaration.name)) names.set(declaration.name.text, statement);
    }
  }
  if (!names.has(name)) return text;
  const selected = new Set();
  function include(statement) {
    if (selected.has(statement)) return;
    selected.add(statement);
    function walk(node) {
      if (ts.isIdentifier(node) && names.has(node.text)) include(names.get(node.text));
      ts.forEachChild(node, walk);
    }
    walk(statement);
  }
  include(names.get(name));
  return file.statements.filter(statement => selected.has(statement) || ts.isImportDeclaration(statement))
    .map(statement => printer.printNode(ts.EmitHint.Unspecified, statement, file)).join('\n');
}
const reference = { components: {}, examples: {}, supportingTypes: declarations['invariant/types.d.ts'] };
for (const component of catalog.components) {
  const source = component.source.replace('packages/highway-react/src/', '').replace(/\.[jt]sx?$/, '') + '.d.ts';
  if (!declarations[source]) errors.push(`Missing declaration for ${component.export}`);
  reference.components[component.export] = { source, declaration: declarations[source], displayDeclaration: focusedDeclaration(declarations[source], component.export) };
  for (const example of component.examples ?? []) reference.examples[example] = read(example);
}
artifact('catalog/component-reference.json', JSON.stringify(reference, null, 2) + '\n');
artifact('catalog/api-report.json', JSON.stringify({ packageVersion: catalog.packageVersion, declarations }, null, 2) + '\n');
if (errors.length) throw new Error(errors.join('\n'));
console.log(`Systems ${write ? 'generated' : 'verified'}: ${catalog.components.length} contracts, ${Object.keys(declarations).length} declaration modules. API changes require review.`);
